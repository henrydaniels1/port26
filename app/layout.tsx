import type { Metadata } from "next";
import { Geist, Geist_Mono, Big_Shoulders_Inline, Space_Grotesk } from "next/font/google";
import "./globals.css";
import { InlineScript } from "./components/InlineScript";
import { ChatBox } from "./components/ChatBox";
import { ThemeProvider } from "./components/ThemeProvider";

const bigShouldersInline = Big_Shoulders_Inline({
  variable: "--font-big-shoulders-inline",
  subsets: ["latin"],
  weight: "700",
});

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Premium UI font used for navigation links, section labels and the hero
// subtitle. Intentionally lighter than the display faces already in use.
const spaceGrotesk = Space_Grotesk({
  variable: "--font-space-grotesk",
  subsets: ["latin"],
  weight: ["400", "500", "600", "700"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// Synchronous, dependency-free theme bootstrapper. Runs in <head> before the
// first paint so there is never a flash of the wrong theme: it honours a
// saved preference, else falls back to the OS colour-scheme preference.
const themeInitScript = `(function(){try{var s=localStorage.getItem('theme');var t=s==='dark'||s==='light'?s:(window.matchMedia&&window.matchMedia('(prefers-color-scheme: dark)').matches?'dark':'light');document.documentElement.dataset.theme=t;}catch(e){document.documentElement.dataset.theme='dark';}})();`;

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} ${bigShouldersInline.variable} ${spaceGrotesk.variable} h-full antialiased`}
    >
      <head>
        <InlineScript html={themeInitScript} />
      </head>
      <body className="min-h-full flex flex-col">
        <ThemeProvider>{children}<ChatBox /></ThemeProvider>
      </body>
    </html>
  );
}
